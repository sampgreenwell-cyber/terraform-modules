<#
.SYNOPSIS
    One-time setup for a service repo generated by the gmnupr Backstage template.

.DESCRIPTION
    - Confirms the repo is private and owned by the lab GitHub account.
    - Reads the repo's OIDC subject prefix (repo:<owner>/<repo>, or the immutable
      repo:<owner>@<id>/<repo>@<id> form) and adds a federated credential to the lab
      build identity for pushes to master, so the build can push to the lab ACR.
    - Creates the repo's GitHub environment lab-release and a second federated credential
      for it: release builds (releases/* branches, v* tags) run in that environment,
      because Azure federated credentials allow no wildcard subjects.
    - Sets repo variables AZURE_CLIENT_ID, AZURE_TENANT_ID, AZURE_SUBSCRIPTION_ID,
      LAB_ACR_NAME, VWSTATE_LAB_REPO, and secret VWSTATE_LAB_DISPATCH_TOKEN (a
      fine-grained token you create once, scoped to vwstate-lab with Actions: write).

.EXAMPLE
    .\Initialize-LabRepo.ps1 -Repo gemini-claimsx -DispatchTokenFile C:\secure\vwstate-lab-dispatch.txt -WhatIf
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [Parameter(Mandatory)][ValidatePattern('^[A-Za-z0-9][A-Za-z0-9._-]{0,99}$')][string]$Repo,
    [Parameter(Mandatory)][string]$DispatchTokenFile
)

$ErrorActionPreference = 'Stop'
. "$PSScriptRoot\LabCommon.ps1"

Assert-LabTarget
$vars = Read-LabVars
$out = Get-LabOutputs
$full = "$($vars.github_owner)/$Repo"

$ErrorActionPreference = 'Continue'
$json = & gh repo view $full --json visibility,owner 2>$null | Out-String
$ErrorActionPreference = 'Stop'
if ($LASTEXITCODE -ne 0) { throw "Repo $full not found (create it first)" }
$info = $json | ConvertFrom-Json
if ($info.owner.login -ne $vars.github_owner) { throw "Repo owner is $($info.owner.login), not the lab account" }
if ($info.visibility -ne 'PRIVATE') { throw "Repo $full is $($info.visibility); lab repos must be private" }
if (-not (Test-Path $DispatchTokenFile)) { throw "Dispatch token file not found: $DispatchTokenFile" }

# OIDC subject prefix: read it rather than assume it (GP#1 lesson: AADSTS700213).
$sub = (& gh api "repos/$full/actions/oidc/customization/sub" | Out-String) | ConvertFrom-Json
if ($sub.PSObject.Properties.Name -contains 'sub_claim_prefix' -and $sub.sub_claim_prefix) {
    $prefix = $sub.sub_claim_prefix
}
elseif ($sub.use_default) {
    $prefix = "repo:$full"
}
else {
    throw "Repo $full uses a custom OIDC subject template ($($sub | ConvertTo-Json -Compress)); set the credential by hand."
}
$repoSlug = $Repo -replace '[^A-Za-z0-9-]', '-'
$creds = [ordered]@{
    ("gh-$repoSlug-master")  = "${prefix}:ref:refs/heads/master"
    ("gh-$repoSlug-release") = "${prefix}:environment:lab-release"
}

if ($PSCmdlet.ShouldProcess("$full environment lab-release", 'Create if missing')) {
    Invoke-LabNative gh @('api', '-X', 'PUT', "repos/$full/environments/lab-release", '--silent')
}
foreach ($credName in $creds.Keys) {
    $name = if ($credName.Length -gt 120) { $credName.Substring(0, 120) } else { $credName }
    if ($PSCmdlet.ShouldProcess("$($out.build_identity_name) federated credential $name", "subject $($creds[$credName])")) {
        # create is a PUT: re-running updates the credential in place.
        Invoke-LabNative az @('identity', 'federated-credential', 'create', '--subscription', $vars.subscription_id,
            '--resource-group', $out.resource_group, '--identity-name', $out.build_identity_name, '--name', $name,
            '--issuer', 'https://token.actions.githubusercontent.com', '--subject', $creds[$credName],
            '--audiences', 'api://AzureADTokenExchange', '--only-show-errors', '-o', 'none')
    }
}

$repoVars = [ordered]@{
    AZURE_CLIENT_ID       = $out.build_client_id
    AZURE_TENANT_ID       = $vars.tenant_id
    AZURE_SUBSCRIPTION_ID = $vars.subscription_id
    LAB_ACR_NAME          = $out.acr_name
    VWSTATE_LAB_REPO      = "$($vars.github_owner)/vwstate-lab"
}
foreach ($k in $repoVars.Keys) {
    if ($PSCmdlet.ShouldProcess("$full variable $k", 'Set')) {
        Invoke-LabNative gh @('variable', 'set', $k, '--repo', $full, '--body', $repoVars[$k])
    }
}
if ($PSCmdlet.ShouldProcess("$full secret VWSTATE_LAB_DISPATCH_TOKEN", 'Set from file')) {
    # Hand gh the file's exact bytes. Piping a string from Windows PowerShell adds a line
    # ending (and, in some hosts, a byte-order mark) that gh stores as part of the secret,
    # so the service build's dispatch gets HTTP 401. The file must hold only the token.
    $token = Get-Content -Raw $DispatchTokenFile
    if ($token -ne $token.Trim()) { throw "Dispatch token file has leading or trailing whitespace: $DispatchTokenFile" }
    Remove-Variable token
    & cmd /c "gh secret set VWSTATE_LAB_DISPATCH_TOKEN --repo $full < `"$((Resolve-Path $DispatchTokenFile).Path)`""
    if ($LASTEXITCODE -ne 0) { throw 'Could not set VWSTATE_LAB_DISPATCH_TOKEN' }
}
if ($WhatIfPreference) { return }
Write-Host "Repo $full is ready: pushes to master can publish to $($out.acr_name) and record versions in vwstate-lab."
